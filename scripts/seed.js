import { ObjectId } from "mongodb";
import { loadConfig } from "../server/config.js";
import { connectDatabase } from "../server/db.js";
import { passwordHash, randomToken, STAFF_ROLES } from "../server/security.js";
import { menu, sampleReviews } from "./menu-data.js";
import { restaurantDefaults } from "../server/restaurant.js";

const demo = process.argv.includes("--demo");
const config = loadConfig();
const store = await connectDatabase(config);
try {
  const existing = new Set(
    (await store.staff.find({}).toArray()).map((user) => user.username),
  );
  const newStaff = STAFF_ROLES.filter((role) => !existing.has(role)).map(
    (role) => {
      const key = "STAFF_" + role.toUpperCase() + "_PASSWORD";
      const password = process.env[key];
      if (!password || password.length < 12 || password.length > 128) {
        throw new Error(
          `${key} must contain 12–128 characters. Run npm run setup for a fresh environment.`,
        );
      }
      return { role, password };
    },
  );
  await Promise.all(
    newStaff.map(async ({ role, password }) => {
      await store.staff.updateOne(
        { username: role },
        {
          $setOnInsert: {
            username: role,
            role,
            passwordHash: await passwordHash(password),
            active: true,
          },
        },
        { upsert: true },
      );
    }),
  );

  await store.dishes.bulkWrite(
    menu.map((dish) => ({
      updateOne: {
        filter: { _id: dish._id },
        update: { $setOnInsert: dish },
        upsert: true,
      },
    })),
  );
  // Add fields introduced in v2 while preserving existing menu edits.
  for (const dish of menu) {
    for (const field of ["serves", "spice", "variants", "addons"]) {
      await store.dishes.updateOne(
        { _id: dish._id, [field]: { $exists: false } },
        { $set: { [field]: dish[field] } },
      );
    }
  }
  await store.settings.updateOne(
    { _id: "restaurant" },
    { $setOnInsert: restaurantDefaults },
    { upsert: true },
  );
  await store.eventLocks.updateOne(
    { _id: "dhanmondi-dining" },
    { $setOnInsert: { revision: 0 } },
    { upsert: true },
  );
  await store.tables.bulkWrite(
    Array.from({ length: 6 }, (_, index) => {
      const number = "T" + String(index + 1).padStart(2, "0");
      const open = demo && index < 2;
      return {
        updateOne: {
          filter: { number },
          update: {
            $setOnInsert: {
              number,
              billingState: "open",
              qrToken: randomToken(24),
              activeVisitId: open ? new ObjectId() : null,
              openedAt: open ? new Date() : null,
              revision: 0,
            },
          },
          upsert: true,
        },
      };
    }),
  );
  if (demo) {
    const names = new Map(menu.map((dish) => [dish._id, dish.name]));
    await store.reviews.bulkWrite(
      sampleReviews.map(([dishId, rating, comment], index) => {
        const orderId = new ObjectId(
          "ffffffffffffffff" + index.toString(16).padStart(8, "0"),
        );
        return {
          updateOne: {
            filter: { orderId, dishId },
            update: {
              $setOnInsert: {
                orderId,
                dishId,
                rating,
                comment,
                dishName: names.get(dishId),
                source: "sample",
                status: "approved",
                createdAt: new Date(Date.now() - (index + 1) * 86400000),
              },
            },
            upsert: true,
          },
        };
      }),
    );
  }
  console.log(
    demo
      ? "Demo menu, tables and labeled sample reviews are ready. Run npm run tables for table links."
      : "Menu, tables and staff accounts are ready. Open a table in the admin workspace before using it.",
  );
  console.log(
    "Staff usernames: admin, kitchen, waiter, cashier. Passwords are in your local .env when generated by setup.",
  );
} finally {
  await store.client.close();
}
